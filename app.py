import turtle
from turtle import *
t=Turtle()
t.shape('turtle')
def square(x):
    t.forward(x)
    t.right(90)
    t.forward(x) 
    t.right(90)
    t.forward(x)
    t.right(90)
    t.forward(x)
#square(200)
def triangle(x):
    t.forward(x)
    t.right(120)
    t.forward(x)
    t.right(120)
    t.forward(x)
 #triangle(200)
